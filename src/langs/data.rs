/// How a language embeds code in others, whose regions are counted by those languages' rules.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Embedding {
	/// `<script>` and `<style>` elements.
	Html,
	/// HTML's elements, and a TypeScript frontmatter between `---` lines.
	Astro,
	/// Fenced code blocks, and YAML (`---`) or TOML (`+++`) frontmatter.
	Markdown,
	/// `[source,python]` listing blocks, and fenced code blocks.
	AsciiDoc,
	/// `#+BEGIN_SRC python` blocks.
	Org,
	/// `.. code-block:: python` directives.
	ReStructuredText,
	/// HTML outside `<?php ... ?>` tags, with HTML's own elements inside it.
	Php,
}

/// When content has to show one of a language's keywords for a file to be that language.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RequireKeywords {
	/// Never: the language is the default among those sharing a pattern.
	Never,
	/// Where the file's pattern is shared with other languages (C++ for a `.h`), but not for its own (`.cpp`).
	Shared,
	/// Even for a pattern only this language has, which others' files often use too (RPM Spec's `.spec`).
	Always,
}

/// A language's heredocs (`<<EOF`): string literals whose body runs from the next line to a line holding just the terminator. They differ in where a space may come between the opener and the terminator, which tells them apart from a shift or append (`x << y`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Heredoc {
	/// `<<EOF`, `<<-EOF`, `<< 'EOF'`: spaces allowed.
	Shell,
	/// `<<EOF`, `<<~EOF`, `<< "EOF"`: a space only before a quoted terminator.
	Perl,
	/// `<<EOF`, `<<~EOF`, `<<-'EOF'`: no space, as `x << y` appends.
	Ruby,
	/// `<<<EOT`, `<<< "EOT"`: spaces allowed, as `<<<` is nothing else.
	Php,
}

impl Heredoc {
	#[must_use]
	pub const fn opener(self) -> &'static str {
		match self {
			Self::Php => "<<<",
			Self::Shell | Self::Perl | Self::Ruby => "<<",
		}
	}
}

/// A table from a file name or extension to its languages, generated by the build script, so the program has nothing to build when it starts.
pub struct NameTable {
	/// Every name, one after another.
	names: &'static str,
	/// Where each entry's name ends in `names`.
	name_ends: &'static [u32],
	/// Every entry's language indexes, one after another.
	langs: &'static [u16],
	/// Where each entry's languages end in `langs`.
	lang_ends: &'static [u16],
	/// A hash table with linear probing. A slot holds an entry's position plus one, or zero if it's empty.
	slots: &'static [u16],
}

impl NameTable {
	/// The indexes of the languages that `name` belongs to.
	pub fn get(&self, name: &str) -> Option<&'static [u16]> {
		let hash = name.bytes().fold(0x811c_9dc5_u32, |hash, byte| (hash ^ u32::from(byte)).wrapping_mul(0x0100_0193));
		let mask = self.slots.len() - 1;
		let mut slot = hash as usize & mask;
		loop {
			let entry = usize::from(self.slots[slot]).checked_sub(1)?;
			let start = entry.checked_sub(1).map_or(0, |previous| self.name_ends[previous] as usize);
			if &self.names[start..self.name_ends[entry] as usize] == name {
				let start = entry.checked_sub(1).map_or(0, |previous| usize::from(self.lang_ends[previous]));
				return Some(&self.langs[start..usize::from(self.lang_ends[entry])]);
			}
			slot = (slot + 1) & mask;
		}
	}
}

